// ---------- profile managers: user-level generated agent file ----------

const marker = (slug: string) => `<!-- generated by RemoteCLI from template ${slug}; edit template, not this file -->`;
const generatedAgent = (name: string, slug = name) => `---\nname: ${name}\ndescription: d\n---\n${marker(slug)}\n\nDo it.\n`;

test('isUserGeneratedAgent is true for a generated ~/.claude/agents file, false without the marker, with a foreign marker, or for an unknown or unsafe name', async () => {
  await withRig(async (rig) => {
    writeAgent(userAgents(rig), 'manager.md', generatedAgent('manager'));
    writeAgent(userAgents(rig), 'handmade.md', '---\nname: handmade\ndescription: d\n---\nNo marker here.\n');
    writeAgent(userAgents(rig), 'copy.md', generatedAgent('copy', 'other-slug'));
    writeAgent(userAgents(rig), 'renamed.md', generatedAgent('different', 'renamed'));
    assert.equal(await rig.claudeAgents.isUserGeneratedAgent('manager'), true);
    assert.equal(await rig.claudeAgents.isUserGeneratedAgent('handmade'), false);
    assert.equal(await rig.claudeAgents.isUserGeneratedAgent('copy'), false);
    assert.equal(await rig.claudeAgents.isUserGeneratedAgent('different'), false, 'the front matter name must be the file\'s own slug');
    assert.equal(await rig.claudeAgents.isUserGeneratedAgent('missing'), false);
    assert.equal(await rig.claudeAgents.isUserGeneratedAgent('../manager'), false);
  });
});

test('a project file of the same name shadows the user file and disqualifies it, readable or not', async () => {
  const project = makeTempDir('project-');
  try {
    await withRig(async (rig) => {
      writeAgent(userAgents(rig), 'manager.md', generatedAgent('manager'));
      const projectAgents = path.join(project, '.claude', 'agents');
      assert.equal(await rig.claudeAgents.isUserGeneratedAgent('manager', project), true, 'no project file: the user file runs');
      writeAgent(projectAgents, 'manager.md', '---\nname: manager\ndescription: d\n---\nHandmade shadow.\n');
      assert.equal(await rig.claudeAgents.isUserGeneratedAgent('manager', project), false);
      writeAgent(projectAgents, 'manager.md', generatedAgent('manager'));
      assert.equal(await rig.claudeAgents.isUserGeneratedAgent('manager', project), false, 'even a generated project file is not the user-level one');
      writeAgent(projectAgents, 'manager.md', 'no front matter');
      assert.equal(await rig.claudeAgents.isUserGeneratedAgent('manager', project), false, 'an unreadable shadow still shadows');
    });
  } finally { removeDir(project); }
});

// ---------- deleting a generated agent file ----------

test('deleteGenerated removes a generated user or project file and refuses handmade, foreign-marker, missing and unsafe targets', async () => {
  const project = makeTempDir('project-');
  try {
    await withRig(async (rig) => {
      const projectAgents = path.join(project, '.claude', 'agents');
      writeAgent(userAgents(rig), 'manager.md', generatedAgent('manager'));
      writeAgent(userAgents(rig), 'handmade.md', '---\nname: handmade\ndescription: d\n---\nNo marker.\n');
      writeAgent(userAgents(rig), 'copy.md', generatedAgent('copy', 'other-slug'));
      writeAgent(projectAgents, 'worker.md', generatedAgent('worker'));

      assert.deepEqual(await rig.claudeAgents.deleteGenerated('user', 'manager'), { deleted: true });
      assert.equal(fs.existsSync(path.join(userAgents(rig), 'manager.md')), false);
      assert.deepEqual(await rig.claudeAgents.deleteGenerated('project', 'worker', project), { deleted: true });
      assert.equal(fs.existsSync(path.join(projectAgents, 'worker.md')), false);

      for (const name of ['handmade', 'copy']) {
        await assert.rejects(rig.claudeAgents.deleteGenerated('user', name), (error: { code?: string }) => error.code === 'AGENT_NOT_GENERATED');
        assert.equal(fs.existsSync(path.join(userAgents(rig), `${name}.md`)), true, `${name} stays`);
      }
      await assert.rejects(rig.claudeAgents.deleteGenerated('user', 'missing'), (error: { code?: string }) => error.code === 'PROFILE_NOT_FOUND');
      await assert.rejects(rig.claudeAgents.deleteGenerated('user', '../manager'), (error: { code?: string }) => error.code === 'INVALID_PROFILE_INPUT');
      await assert.rejects(rig.claudeAgents.deleteGenerated('project', 'worker'), (error: { code?: string }) => error.code === 'INVALID_PROFILE_INPUT');
      await assert.rejects(rig.claudeAgents.deleteGenerated('other', 'worker'), (error: { code?: string }) => error.code === 'INVALID_PROFILE_INPUT');
    });
  } finally { removeDir(project); }
});
