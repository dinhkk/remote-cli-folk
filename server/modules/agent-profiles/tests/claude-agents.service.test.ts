test('listMainAgents carries the group of the template a generated file came from, read live; handmade files and renamed copies carry none', async () => {
  await withRig(async (rig) => {
    const folder = userAgents(rig);
    const marker = (slug: string) => `<!-- generated by RemoteCLI from template ${slug}; edit template, not this file -->`;
    const grouped = rig.service.createTemplate(templateBody({ slug: 'reviewer', group: 'Work' }));
    rig.service.createTemplate(templateBody({ slug: 'plain-one' }));
    writeAgent(folder, 'reviewer.md', `---\nname: reviewer\ndescription: d\n---\n${marker('reviewer')}\n\nBody`);
    writeAgent(folder, 'plain-one.md', `---\nname: plain-one\ndescription: d\n---\n${marker('plain-one')}\n\nBody`);
    // A generated file whose template was deleted, a handmade file and a renamed copy (its marker names another slug).
    writeAgent(folder, 'orphan.md', `---\nname: orphan\ndescription: d\n---\n${marker('orphan')}\n\nBody`);
    writeAgent(folder, 'mine.md', '---\nname: mine\ndescription: d\n---\nBody');
    writeAgent(folder, 'my-copy.md', `---\nname: my-copy\ndescription: d\n---\n${marker('reviewer')}\n\nBody`);
    const groupsOf = async () => Object.fromEntries((await rig.claudeAgents.listMainAgents(path.join(rig.root, 'proj'))).map((agent) => [agent.name, agent.group]));

    assert.deepEqual(await groupsOf(), { 'reviewer': 'Work', 'plain-one': undefined, orphan: undefined, mine: undefined, 'my-copy': undefined });
    const noGroupKey = (await rig.claudeAgents.listMainAgents(path.join(rig.root, 'proj'))).find((agent) => agent.name === 'mine');
    assert.equal(Object.hasOwn(noGroupKey ?? {}, 'group'), false, 'no group key at all when there is none');

    // Editing the template moves the agent at once: nothing is regenerated.
    rig.service.updateTemplate(grouped.id, templateBody({ slug: 'reviewer', group: 'Review', rev: 1 }));
    assert.equal((await groupsOf())['reviewer'], 'Review');
    rig.service.updateTemplate(grouped.id, templateBody({ slug: 'reviewer', rev: 2 }));
    assert.equal((await groupsOf())['reviewer'], undefined, 'clearing the group puts it back among the ungrouped');
  });
});

