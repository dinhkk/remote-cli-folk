import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import test from 'node:test';

import { makeTempDir, removeDir } from './profile-fixtures.js';
import { makeServiceRig, templateBody } from './service-rig.js';

type Rig = ReturnType<typeof makeServiceRig>;

async function withRig(run: (rig: Rig) => Promise<void>, sdkAgents = [{ name: 'Explore', description: 'Fast search', model: 'haiku' }, { name: 'Plan', description: 'Plans' }]) {
  const rig = makeServiceRig({ sdkAgents });
  try { await run(rig); } finally { rig.cleanup(); }
}

function writeAgent(directory: string, file: string, text: string): void {
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, file), text);
}

const userAgents = (rig: Rig) => path.join(rig.claudeHome, 'agents');

test('lists built-ins from the SDK and user agent files with their prompt, tools and model', async () => {
  await withRig(async (rig) => {
    writeAgent(userAgents(rig), 'reviewer.md', '---\nname: code-reviewer\ndescription: Reviews code\ntools: Read, Grep\nmodel: sonnet\n---\nYou review code.\n');
    const { items, builtinSource } = await rig.claudeAgents.list();
    assert.equal(builtinSource, 'sdk');
    assert.deepEqual(items.map((item) => [item.source, item.name]), [['builtin', 'Explore'], ['builtin', 'Plan'], ['user', 'code-reviewer']]);
    const file = items[2];
    assert.deepEqual([file.description, file.tools, file.model, file.prompt], ['Reviews code', ['Read', 'Grep'], 'sonnet', 'You review code.']);
    assert.equal(items[0].model, 'haiku');
    assert.equal(items[0].prompt, undefined, 'built-ins expose no prompt');
  });
});

