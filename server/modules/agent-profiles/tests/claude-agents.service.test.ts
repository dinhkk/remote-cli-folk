test('when the SDK fails the static built-in list is used (and retried after a minute)', async () => {
  await withRig(async (rig) => {
    rig.state.sdkFails = true;
    const listing = await rig.claudeAgents.list();
    assert.equal(listing.builtinSource, 'fallback');
    assert.ok(listing.items.some((item) => item.source === 'builtin' && item.name === 'Explore'));
    await rig.claudeAgents.list();
    assert.equal(rig.state.sdkCalls, 1, 'failure is cached briefly');
    rig.state.sdkFails = false;
    rig.state.clock += 61 * 1000;
    assert.equal((await rig.claudeAgents.list()).builtinSource, 'sdk');
  });
});

test('a lookup that never settles times out to the static list and does not hang later calls', async () => {
  await withRig(async (rig) => {
    rig.state.sdkHangs = true;
    const started = Date.now();
    const listing = await rig.claudeAgents.list();
    assert.ok(Date.now() - started < 2000, 'returned after the short test timeout, not never');
    assert.equal(listing.builtinSource, 'fallback');
    assert.ok(listing.items.some((item) => item.name === 'Explore'));
    // The failure is cached briefly, so the next call answers at once instead of waiting again.
    const second = Date.now();
    await rig.claudeAgents.list();
    assert.ok(Date.now() - second < 40);
    assert.equal(rig.state.sdkCalls, 1);
    // After the failure cache expires, a healthy lookup works again.
    rig.state.sdkHangs = false;
    rig.state.clock += 61 * 1000;
    assert.equal((await rig.claudeAgents.list()).builtinSource, 'sdk');
  });
});

