test('a broken agent file becomes an error entry without breaking the list', async () => {
  await withRig(async (rig) => {
    writeAgent(userAgents(rig), 'good.md', '---\nname: good\ndescription: ok\n---\nBody');
    writeAgent(userAgents(rig), 'noname.md', '---\ndescription: no name here\n---\nBody');
    writeAgent(userAgents(rig), 'bad-yaml.md', '---\nname: [unclosed\n  : : :\n---\nBody');
    writeAgent(userAgents(rig), 'notes.txt', 'ignored');
    const { items } = await rig.claudeAgents.list();
    const files = items.filter((item) => item.source === 'user');
    assert.deepEqual(files.map((item) => item.name).sort(), ['bad-yaml', 'good', 'noname']);
    assert.equal(files.find((item) => item.name === 'good')?.error, undefined);
    assert.match(files.find((item) => item.name === 'noname')?.error ?? '', /no "name"/);
    assert.ok(files.find((item) => item.name === 'bad-yaml')?.error);
  });
});

