test('a file with the RemoteCLI marker is listed as generated (with its template), any other file as handmade', async () => {
  await withRig(async (rig) => {
    const folder = path.join(userAgents(rig));
    const marker = (slug: string) => `<!-- generated by RemoteCLI from template ${slug}; edit template, not this file -->`;
    writeAgent(folder, 'gen.md', `---\nname: gen\ndescription: d\n---\n${marker('gen')}\n\nBody`);
    writeAgent(folder, 'mine.md', '---\nname: mine\ndescription: d\n---\nBody');
    // The marker only counts on a line of its own, not quoted inside the prose.
    writeAgent(folder, 'quote.md', `---\nname: quote\ndescription: d\n---\nSee "${marker('quote')}" in docs`);
    // ... nor further down the body, even on a line of its own.
    writeAgent(folder, 'midfile.md', `---\nname: midfile\ndescription: d\n---\nIntro text.\n\n${marker('midfile')}\n\nBody`);
    // ... and it must name the file's own slug: a copy renamed by hand keeps the old marker and is handmade.
    writeAgent(folder, 'my-copy.md', `---\nname: my-copy\ndescription: d\n---\n${marker('gen')}\n\nBody`);
    const { items } = await rig.claudeAgents.list();
    const files = Object.fromEntries(items.filter((item) => item.source === 'user').map((item) => [item.name, item]));
    assert.deepEqual([files.gen.generated, files.gen.generatedFrom], [true, 'gen']);
    assert.equal(files.gen.path, path.join(folder, 'gen.md'));
    assert.equal(files.mine.generated, false);
    assert.equal(files.mine.generatedFrom, undefined);
    for (const name of ['quote', 'midfile', 'my-copy']) {
      assert.equal(files[name].generated, false, `${name} is handmade`);
      assert.equal(files[name].generatedFrom, undefined);
    }
    assert.equal(items.find((item) => item.source === 'builtin')?.generated, false);
  });
});

test('hasAgentFile finds a readable agent in the project or user folder by its front matter name, never a built-in', async () => {
  await withRig(async (rig) => {
    const project = path.join(rig.root, 'proj');
    writeAgent(path.join(project, '.claude', 'agents'), 'file-name.md', '---\nname: orchestrator\ndescription: d\n---\nB');
    writeAgent(userAgents(rig), 'u.md', '---\nname: shared\ndescription: d\n---\nB');
    writeAgent(userAgents(rig), 'broken.md', '---\ndescription: no name\n---\nB');
    assert.equal(await rig.claudeAgents.hasAgentFile('orchestrator', project), true);
    assert.equal(await rig.claudeAgents.hasAgentFile('orchestrator'), false, 'a project agent is not visible without the project folder');
    assert.equal(await rig.claudeAgents.hasAgentFile('shared', project), true);
    assert.equal(await rig.claudeAgents.hasAgentFile('broken', project), false, 'an unreadable file does not count');
    assert.equal(await rig.claudeAgents.hasAgentFile('Explore', project), false, 'built-ins do not count');
    assert.equal(rig.state.sdkCalls, 0, 'the existence check never reaches the SDK');
  });
});

