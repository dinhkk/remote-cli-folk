import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';

import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { InMemoryTransport } from '@modelcontextprotocol/sdk/inMemory.js';

import type { AnyRecord, SessionAgentSnapshot } from '@/shared/types.js';

// The agent-profiles module reads its data directory and the Claude home (`~/.claude`) when it is first imported (on the
// first call below), so the environment is prepared before any run is built.
const dataRoot = fs.mkdtempSync(path.join(os.tmpdir(), 'claude-profiles-mcp-'));
const profilesRoot = path.join(dataRoot, 'agent-profiles');
const homeDirectory = path.join(dataRoot, 'home');
const projectDirectory = path.join(dataRoot, 'project');
process.env.AGENT_PROFILES_DIR = profilesRoot;
process.env.HOME = homeDirectory;
process.env.USERPROFILE = homeDirectory;
const { resolveProfilesAgentName, withProfilesMcpServer, withProfilesToolsAllowed } = await import('@/modules/providers/list/claude/claude-profiles-mcp.js');

test.after(() => fs.rmSync(dataRoot, { recursive: true, force: true }));

const userAgents = path.join(homeDirectory, '.claude', 'agents');
const projectAgents = path.join(projectDirectory, '.claude', 'agents');
const generated = (name: string) => `---\nname: ${name}\ndescription: d\n---\n<!-- generated by RemoteCLI from template ${name}; edit template, not this file -->\n\nManage.\n`;
const handmade = (name: string) => `---\nname: ${name}\ndescription: d\n---\nHandmade.\n`;
const write = (directory: string, name: string, text: string) => {
  fs.mkdirSync(directory, { recursive: true });
  fs.writeFileSync(path.join(directory, `${name}.md`), text);
};
const setSettings = (value: unknown) => {
  fs.mkdirSync(profilesRoot, { recursive: true });
  fs.writeFileSync(path.join(profilesRoot, 'settings.json'), JSON.stringify(value));
};
const allow = (...names: string[]) => setSettings({ rev: 1, updatedAt: '', hiddenClaudeAgents: [], profileManagerAgents: names });
const scoped = (agentName: string | null): SessionAgentSnapshot => ({ agentName, hiddenClaudeAgents: [] });

write(userAgents, 'manager', generated('manager'));
write(userAgents, 'worker', generated('worker'));
write(userAgents, 'hand', handmade('hand'));
write(projectAgents, 'shadowed', handmade('shadowed'));
write(userAgents, 'shadowed', generated('shadowed'));

test('a local run of an allowlisted main agent that resolves to the user-level generated file gets the profiles server', async () => {
  allow('manager');
  assert.equal(await resolveProfilesAgentName(scoped('manager'), 'local', projectDirectory), 'manager');
  assert.equal(await resolveProfilesAgentName(scoped('manager'), 'local', undefined), 'manager', 'no folder is fine');
});

test('a remote, unknown, absent or forged origin never gets it (fail closed)', async () => {
  allow('manager');
  for (const origin of ['remote', undefined, null, '', 'LOCAL', 'local ', 'bridge', 1, true, { origin: 'local' }, ['local']]) {
    assert.equal(await resolveProfilesAgentName(scoped('manager'), origin, projectDirectory), undefined, JSON.stringify(origin));
  }
});

test('an agent that is not on the allowlist, a chat without a main agent, and a name that is not a generated user file get nothing', async () => {
  allow('manager');
  assert.equal(await resolveProfilesAgentName(scoped('worker'), 'local', projectDirectory), undefined, 'a generated agent that is not allowlisted');
  assert.equal(await resolveProfilesAgentName(scoped(null), 'local', projectDirectory), undefined);
  assert.equal(await resolveProfilesAgentName(undefined, 'local', projectDirectory), undefined);
  assert.equal(await resolveProfilesAgentName(scoped(''), 'local', projectDirectory), undefined);
  allow('hand', 'ghost');
  assert.equal(await resolveProfilesAgentName(scoped('hand'), 'local', projectDirectory), undefined, 'allowlisted but handmade (no marker)');
  assert.equal(await resolveProfilesAgentName(scoped('ghost'), 'local', projectDirectory), undefined, 'allowlisted but no file at all');
});

test('a project-level file of the same name shadows the user file and does not qualify', async () => {
  allow('shadowed');
  assert.equal(await resolveProfilesAgentName(scoped('shadowed'), 'local', projectDirectory), undefined);
  assert.equal(await resolveProfilesAgentName(scoped('shadowed'), 'local', path.join(dataRoot, 'other-project')), 'shadowed', 'another folder has no shadow');
});

test('unreadable or malformed settings mean no tools and never an exception', async () => {
  for (const bad of ['manager', [1], { manager: true }, null]) {
    setSettings({ rev: 1, updatedAt: '', hiddenClaudeAgents: [], profileManagerAgents: bad });
    assert.equal(await resolveProfilesAgentName(scoped('manager'), 'local', projectDirectory), undefined, JSON.stringify(bad));
  }
  fs.writeFileSync(path.join(profilesRoot, 'settings.json'), 'not json');
  assert.equal(await resolveProfilesAgentName(scoped('manager'), 'local', projectDirectory), undefined);
  // A folder that is not absolute cannot be read as a project folder: also "no", also no throw.
  allow('manager');
  assert.equal(await resolveProfilesAgentName(scoped('manager'), 'local', 'relative/folder'), undefined);
});

test('a settings file from before the allowlist existed gives no tools', async () => {
  setSettings({ rev: 2, updatedAt: '', hiddenClaudeAgents: ['Plan'] });
  assert.equal(await resolveProfilesAgentName(scoped('manager'), 'local', projectDirectory), undefined);
});

test('the server joins the configured servers (replacing one called profiles), and the four tools are pre-approved only when attached', async () => {
  const configured: AnyRecord = { docs: { type: 'stdio', command: 'docs-mcp' }, profiles: { type: 'stdio', command: 'someone-elses' } };
  const merged = await withProfilesMcpServer(configured, 'manager');
  assert.deepEqual(Object.keys(merged ?? {}).sort(), ['docs', 'profiles']);
  assert.equal(merged?.profiles.type, 'sdk');
  assert.equal(merged?.docs, configured.docs);
  assert.equal(configured.profiles.type, 'stdio', 'the loaded config is not mutated');
  assert.equal(await withProfilesMcpServer(configured, undefined), configured);
  assert.equal(await withProfilesMcpServer(null, undefined), null);

  const approved = withProfilesToolsAllowed(['Read', 'mcp__profiles__profiles_list'], 'manager');
  assert.deepEqual(approved, ['Read', 'mcp__profiles__profiles_list', 'mcp__profiles__profiles_get', 'mcp__profiles__profiles_preview', 'mcp__profiles__profiles_propose']);
  const untouched = ['Read'];
  assert.equal(withProfilesToolsAllowed(untouched, undefined), untouched);
  assert.deepEqual(untouched, ['Read']);
});

test('the attached server stages a proposal as the main agent and writes only a pending file, whatever the run\'s permission settings', async () => {
  allow('manager');
  const servers = await withProfilesMcpServer(null, 'manager');
  const server = servers?.profiles as { instance: { connect(transport: unknown): Promise<void>; close(): Promise<void> } };
  const client = new Client({ name: 'test-client', version: '1.0.0' });
  const [clientTransport, serverTransport] = InMemoryTransport.createLinkedPair();
  await Promise.all([server.instance.connect(serverTransport), client.connect(clientTransport)]);
  try {
    const result = await client.callTool({
      name: 'profiles_propose',
      arguments: { changeset: { upsert: { templates: [{ slug: 'helper', family: 'worker', name: 'Helper', description: '', instructions: 'Help.', tools: ['Read'] }] } } },
    }) as { content: { text: string }[]; isError?: boolean };
    assert.equal(result.isError, undefined, result.content[0]?.text);
    const pendingFiles = fs.readdirSync(path.join(profilesRoot, 'pending'));
    assert.equal(pendingFiles.length, 1);
    assert.equal(JSON.parse(fs.readFileSync(path.join(profilesRoot, 'pending', pendingFiles[0]), 'utf8')).agentName, 'manager');
    assert.equal(fs.existsSync(path.join(profilesRoot, 'templates')), false, 'no template was written');
  } finally {
    await client.close().catch(() => undefined);
    await server.instance.close().catch(() => undefined);
  }
});
